create or replace function public.return_transferred_asset_to_stock(
  p_asset_tag text,
  p_employee_uuid uuid,
  p_return_date timestamptz,
  p_received_by text
)
returns void
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_asset_id uuid;
  v_condition asset_condition;
begin
  select id, condition
    into v_asset_id, v_condition
    from assets
    where asset_tag = p_asset_tag
      and assigned_to = p_employee_uuid
      and status = 'Assigned'
    for update;

  if not found then
    raise exception 'Asset % is no longer assigned to this employee.', p_asset_tag;
  end if;

  update assets
    set status = 'Available',
        assigned_to = null,
        assigned_date = null,
        updated_at = now()
    where id = v_asset_id;

  update assignments
    set status = 'Returned'
    where asset_id = v_asset_id
      and employee_id = p_employee_uuid
      and status = 'Active';

  insert into returns (
    asset_id,
    employee_id,
    returned_date,
    condition,
    remarks,
    received_by
  )
  values (
    v_asset_id,
    p_employee_uuid,
    p_return_date,
    v_condition,
    'Returned to stock from transfer log',
    p_received_by
  );
end;
$$;

