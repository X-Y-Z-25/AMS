-- Install an atomic asset-transfer transaction and grant the app the access it needs.
-- Run this script in the Supabase SQL Editor for an existing database.

alter table public.assets enable row level security;
alter table public.assignments enable row level security;
alter table public.transfers enable row level security;

alter table public.transfers
  add column if not exists serial_number bigint generated by default as identity;
create unique index if not exists transfers_serial_number_key
  on public.transfers (serial_number);

grant select, update on table public.assets to authenticated;
grant select, insert, update on table public.assignments to authenticated;
grant select, insert on table public.transfers to authenticated;
grant select, insert on table public.returns to authenticated;

drop policy if exists "assets_allow_all_for_dev" on public.assets;
create policy "assets_allow_all_for_dev"
on public.assets
for all
to authenticated
using (true)
with check (true);

drop policy if exists "assignments_allow_all_for_dev" on public.assignments;
create policy "assignments_allow_all_for_dev"
on public.assignments
for all
to authenticated
using (true)
with check (true);

drop policy if exists "transfers_allow_all_for_dev" on public.transfers;
create policy "transfers_allow_all_for_dev"
on public.transfers
for all
to authenticated
using (true)
with check (true);

do $$
declare
  v_transfer record;
begin
  for v_transfer in
    select
      asset.id as asset_id,
      assignment.employee_id as from_employee_id,
      asset.assigned_to as to_employee_id,
      coalesce(asset.assigned_date, asset.updated_at, now()) as transfer_date
    from public.assets as asset
    join public.assignments as assignment
      on assignment.asset_id = asset.id
      and assignment.status = 'Active'
    where asset.status = 'Assigned'
      and asset.assigned_to is not null
      and assignment.employee_id <> asset.assigned_to
      and (
        select count(*)
        from public.assignments as active_assignment
        where active_assignment.asset_id = asset.id
          and active_assignment.status = 'Active'
      ) = 1
      and not exists (
        select 1
        from public.transfers as existing_transfer
        where existing_transfer.asset_id = asset.id
          and existing_transfer.from_employee_id = assignment.employee_id
          and existing_transfer.to_employee_id = asset.assigned_to
      )
  loop
    insert into public.transfers (
      asset_id,
      from_employee_id,
      to_employee_id,
      reason,
      transfer_date,
      status
    )
    values (
      v_transfer.asset_id,
      v_transfer.from_employee_id,
      v_transfer.to_employee_id,
      'Recovered incomplete transfer',
      v_transfer.transfer_date,
      'Completed'
    );

    update public.assignments
      set status = 'Transferred'
      where asset_id = v_transfer.asset_id
        and employee_id = v_transfer.from_employee_id
        and status = 'Active';

    insert into public.assignments (
      asset_id,
      employee_id,
      assigned_date,
      status,
      notes
    )
    select
      v_transfer.asset_id,
      v_transfer.to_employee_id,
      v_transfer.transfer_date,
      'Active',
      'Recovered from incomplete asset transfer'
    where not exists (
      select 1
      from public.assignments as active_assignment
      where active_assignment.asset_id = v_transfer.asset_id
        and active_assignment.employee_id = v_transfer.to_employee_id
        and active_assignment.status = 'Active'
    );
  end loop;
end;
$$;

create or replace function public.transfer_assets_to_employee(
  p_asset_tags text[],
  p_from_employee_uuid uuid,
  p_to_employee_uuid uuid,
  p_to_location public.location_type,
  p_transfer_date timestamptz,
  p_reason text
)
returns void
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_asset_tag text;
  v_asset_id uuid;
  v_transfer_count integer := 0;
begin
  if p_from_employee_uuid is null
    or p_to_employee_uuid is null
    or p_from_employee_uuid = p_to_employee_uuid then
    raise exception 'Select different source and destination employees.';
  end if;

  if coalesce(array_length(p_asset_tags, 1), 0) = 0 then
    raise exception 'Select at least one asset to transfer.';
  end if;

  for v_asset_tag in
    select distinct trim(tag)
    from unnest(p_asset_tags) as tags(tag)
    where trim(tag) <> ''
  loop
    select id
      into v_asset_id
      from public.assets
      where asset_tag = v_asset_tag
        and assigned_to = p_from_employee_uuid
        and status = 'Assigned'
      for update;

    if not found then
      raise exception 'Asset % is no longer assigned to the original employee.', v_asset_tag;
    end if;

    update public.assets
      set assigned_to = p_to_employee_uuid,
          location = p_to_location,
          assigned_date = p_transfer_date,
          updated_at = now()
      where id = v_asset_id;

    insert into public.transfers (
      asset_id,
      from_employee_id,
      to_employee_id,
      reason,
      transfer_date,
      status
    )
    values (
      v_asset_id,
      p_from_employee_uuid,
      p_to_employee_uuid,
      p_reason,
      p_transfer_date,
      'Completed'
    );

    update public.assignments
      set status = 'Transferred'
      where asset_id = v_asset_id
        and employee_id = p_from_employee_uuid
        and status = 'Active';

    insert into public.assignments (
      asset_id,
      employee_id,
      assigned_date,
      status,
      notes
    )
    values (
      v_asset_id,
      p_to_employee_uuid,
      p_transfer_date,
      'Active',
      'Transferred from employee ' || p_from_employee_uuid::text
    );

    v_transfer_count := v_transfer_count + 1;
  end loop;

  if v_transfer_count = 0 then
    raise exception 'Select at least one valid asset to transfer.';
  end if;
end;
$$;

revoke all on function public.transfer_assets_to_employee(
  text[], uuid, uuid, public.location_type, timestamptz, text
) from public;
grant execute on function public.transfer_assets_to_employee(
  text[], uuid, uuid, public.location_type, timestamptz, text
) to authenticated;

create or replace function public.return_transferred_asset_to_stock(
  p_asset_tag text,
  p_employee_uuid uuid,
  p_return_date timestamptz
)
returns void
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_asset_id uuid;
  v_condition public.asset_condition;
begin
  select id, condition
    into v_asset_id, v_condition
    from public.assets
    where asset_tag = p_asset_tag
      and assigned_to = p_employee_uuid
      and status = 'Assigned'
    for update;

  if not found then
    raise exception 'Asset % is no longer assigned to this employee.', p_asset_tag;
  end if;

  update public.assets
    set status = 'Available',
        assigned_to = null,
        assigned_date = null,
        updated_at = now()
    where id = v_asset_id;

  update public.assignments
    set status = 'Returned'
    where asset_id = v_asset_id
      and employee_id = p_employee_uuid
      and status = 'Active';

  insert into public.returns (
    asset_id,
    employee_id,
    returned_date,
    condition,
    remarks
  )
  values (
    v_asset_id,
    p_employee_uuid,
    p_return_date,
    v_condition,
    'Returned to stock from transfer log'
  );
end;
$$;

revoke all on function public.return_transferred_asset_to_stock(
  text, uuid, timestamptz
) from public;
grant execute on function public.return_transferred_asset_to_stock(
  text, uuid, timestamptz
) to authenticated;

notify pgrst, 'reload schema';
